#include <string.h>
#include <inttypes.h>
#include <stdint.h>
#include <stdio.h>
#include <ctype.h>

struct crc_details {
	const char *name;
	uint8_t bits;
	uint64_t polynomial;
	bool reflect;
};

const char *capitalise(const char *str) {
	static char ret[64];
	int i = 0;
	while (i < 64 && i < strlen(str)) {
		ret[i] = toupper(str[i]);
		i++;
	}
	ret[i] = '\0';
	return ret;
}

#define TABLE_LEN(details) ((details).bits >= 8 ? 256u : 1u << (details).bits)
#define MASK(details) ((details).bits == 64 ? ~UINT64_C(0) : (UINT64_C(1) << (details).bits) - UINT64_C(1))
#define HIGH_BIT(details) (UINT64_C(1) << ((details).bits - 1))
#define HIGH_BYTE_OFFSET(details) ((details).bits - 8)
#define TYPE_NAME(details) (\
	(details).bits > 32 ? "uint64_t" :\
	(details).bits > 16 ? "uint32_t" :\
	(details).bits > 8  ? "uint16_t" :\
	"uint8_t"\
)
#define LITERAL_WRAPPER(details) (\
	(details).bits > 32 ? "UINT64_C" :\
	(details).bits > 16 ? "UINT32_C" :\
	(details).bits > 8  ? "UINT16_C" :\
	"UINT8_C"\
)

uint64_t reflect(const uint64_t n, const uint8_t bits) {
	uint64_t r = 0;
	for (uint8_t i = 0; i < bits; i++) {
		r |= (n >> i & 1) << (bits - i - 1);
	}
	if (bits == 64)
		return r;
	return r & ((UINT64_C(1) << bits) - 1);
}
void table_gen(uint64_t *table, const struct crc_details details) {
	const uint64_t polynomial = details.polynomial & MASK(details);

	uint64_t crc;
	for (uint64_t i = 0; i < TABLE_LEN(details); i++) {
		if (details.reflect)
			crc = reflect(i, details.bits);
		else
			crc = i << HIGH_BYTE_OFFSET(details);

		for (int bit = 0; bit < 8; bit++) {
			if (crc & HIGH_BIT(details))
				crc = crc << 1 ^ polynomial;
			else
				crc <<= 1;
		}

		if (details.reflect)
			table[i] = reflect(crc, details.bits);
		else
			table[i] = crc & MASK(details);
	}
}
void power_table_gen(uint64_t *table, uint8_t bits, const struct crc_details details) {
	uint64_t power = (details.bits <= 8) ? details.polynomial : 0x100;
	for (uint8_t i = 0; i < bits; i++) {
		table[i] = power;
		uint64_t n = power, res = 0;
		for (uint64_t j = 0; j < details.bits; j++) {
			if (power & (UINT64_C(1) << j))
				res ^= n;
			if (n & HIGH_BIT(details))
				n = (n << 1) ^ details.polynomial;
			else
				n <<= 1;
			n &= MASK(details);
		}
		power = res;
	}
}
