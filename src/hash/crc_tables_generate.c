void write_details(const struct crc_details details) {
	const char *caps = capitalise(details.name);
	printf("#define %s_BITS %d\n", caps,  details.bits);
	printf("#define %s_POLYNOMIAL %s(0x%"PRIX64")\n", caps, LITERAL_WRAPPER(details), details.polynomial);
	printf("#define %s_NORMALISED_POLYNOMIAL %s(0x%"PRIX64")\n",
		caps, LITERAL_WRAPPER(details), details.reflect ? reflect(details.polynomial, details.bits) : details.polynomial);
	printf("#define %s_REFLECTED %s\n", caps, details.reflect ? "true" : "false");
}
void write_table(const uint64_t *table, size_t table_len, const char *suffix, const struct crc_details details) {
	printf("static constexpr %s %s_%s[%"PRIu64"] = {\n\t", TYPE_NAME(details), details.name, suffix, (uint64_t)table_len);
	for (size_t i = 0; i < table_len; i++) {
		printf("%s(0x%" PRIX64 "),", LITERAL_WRAPPER(details), table[i]);
		if (i != table_len - 1) {
			if (i%4 == 3) {
				printf("\n\t");
			} else {
				printf(" ");
			}
		}
	}
	printf("\n};\n");
}
int main() {
	const struct crc_details details[] = {
		{
			.name = "crc64",
			.bits = 64,
			.polynomial = UINT64_C(0x42F0E1EBA9EA3693),
			.reflect = false
		},
		{
			.name = "crc32",
			.bits = 32,
			.polynomial = UINT64_C(0x1EDC6F41),
			.reflect = true
		},
		{
			.name = "crc24",
			.bits = 24,
			.polynomial = UINT64_C(0x864CFB),
			.reflect = false
		},
		{
			.name = "crc16",
			.bits = 16,
			.polynomial = UINT64_C(0x1021),
			.reflect = true
		},
		{
			.name = "crc8",
			.bits = 8,
			.polynomial = UINT64_C(0x07),
			.reflect = false
		}
	};
	constexpr size_t details_len = sizeof(details)/sizeof(details[0]);
	uint64_t table[256];

	printf("// generated by "__FILE__"\n");
	printf("#ifndef LIBCLOD_CRC_TABLES_H\n");
	printf("#define LIBCLOD_CRC_TABLES_H\n");
	printf("#include <stdint.h>\n\n");
	for (unsigned i = 0; i < details_len; i++) {
		write_details(details[i]);

		table_gen(table, details[i]);
		write_table(table, 256, "table", details[i]);

		power_table_gen(table, 64, details[i]);
		write_table(table, 64, "power_table", details[i]);

		if (i != details_len - 1) printf("\n");
	}
	printf("#endif\n");
}
